"""
Export module for exporting CPU Scheduling results to CSV and PDF.
"""

import io
import csv
from typing import List, Optional
import matplotlib.pyplot as plt
from .models import SimulationResult


def export_results_to_csv(result: SimulationResult) -> str:
    """Exports a single simulation result's process metrics to a CSV string."""
    output = io.StringIO()
    writer = csv.writer(output)

    # Header
    writer.writerow([
        "Process ID", "Arrival Time", "Burst Time", "Priority",
        "Start Time", "Completion Time", "Turnaround Time",
        "Waiting Time", "Response Time"
    ])

    for p in sorted(result.processes, key=lambda x: x.pid):
        writer.writerow([
            p.pid, p.arrival_time, p.burst_time, p.priority,
            p.start_time, p.completion_time, p.turnaround_time,
            p.waiting_time, p.response_time
        ])

    writer.writerow([])
    writer.writerow(["--- Summary Metrics ---"])
    summary = result.get_summary_dict()
    for k, v in summary.items():
        writer.writerow([k, v])

    return output.getvalue()


def export_comparison_to_csv(results: List[SimulationResult]) -> str:
    """Exports comparison metrics across multiple algorithms to a CSV string."""
    output = io.StringIO()
    writer = csv.writer(output)

    writer.writerow([
        "Algorithm", "Total Time", "Idle Time",
        "Avg Waiting Time", "Avg Turnaround Time", "Avg Response Time",
        "CPU Utilization (%)", "Throughput (proc/unit)"
    ])

    for r in results:
        writer.writerow([
            r.algorithm_name,
            r.total_time,
            r.idle_time,
            round(r.avg_waiting_time, 2),
            round(r.avg_turnaround_time, 2),
            round(r.avg_response_time, 2),
            round(r.cpu_utilization, 2),
            round(r.throughput, 4)
        ])

    return output.getvalue()


def _export_pdf_via_reportlab(
    result: SimulationResult,
    fig_gantt: Optional[plt.Figure] = None,
    comparison_results: Optional[List[SimulationResult]] = None
) -> bytes:
    """Generates PDF using ReportLab with tables and Gantt chart image."""
    from reportlab.lib.pagesizes import letter
    from reportlab.lib import colors
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image as RLImage
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    story = []
    styles = getSampleStyleSheet()

    # Custom styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#1E3A8A"),
        spaceAfter=6
    )
    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontSize=10,
        textColor=colors.HexColor("#4B5563"),
        spaceAfter=15
    )
    heading2_style = ParagraphStyle(
        'SectionHeading',
        parent=styles['Heading2'],
        fontSize=13,
        leading=16,
        textColor=colors.HexColor("#1F2937"),
        spaceBefore=12,
        spaceAfter=6
    )
    cell_style = ParagraphStyle(
        'CellText',
        parent=styles['Normal'],
        fontSize=8.5,
        leading=10
    )

    story.append(Paragraph("Smart CPU Scheduling Simulation Report", title_style))
    story.append(Paragraph(f"Algorithm: <b>{result.algorithm_name}</b> | Generated by Smart CPU Scheduling Visualizer", subtitle_style))
    story.append(Spacer(1, 10))

    # Summary Metrics
    story.append(Paragraph("1. Performance Metrics Summary", heading2_style))
    summary_data = [
        ["Metric", "Value", "Metric", "Value"],
        ["Total Execution Time", f"{result.total_time:g} units", "Avg Waiting Time", f"{result.avg_waiting_time:.2f} units"],
        ["Total Idle Time", f"{result.idle_time:g} units", "Avg Turnaround Time", f"{result.avg_turnaround_time:.2f} units"],
        ["CPU Utilization", f"{result.cpu_utilization:.2f}%", "Avg Response Time", f"{result.avg_response_time:.2f} units"],
        ["Throughput", f"{result.throughput:.4f} proc/unit", "Total Processes", f"{len(result.processes)}"]
    ]
    t_summary = Table(summary_data, colWidths=[130, 130, 130, 130])
    t_summary.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#2563EB")),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 9),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#D1D5DB")),
        ('BACKGROUND', (0, 1), (-1, -1), colors.HexColor("#F9FAFB")),
    ]))
    story.append(t_summary)
    story.append(Spacer(1, 14))

    # Process Detail Table
    story.append(Paragraph("2. Process Execution Details", heading2_style))
    proc_headers = ["PID", "Arrival", "Burst", "Priority", "Start", "Completion", "Turnaround", "Waiting", "Response"]
    proc_rows = [proc_headers]
    for p in sorted(result.processes, key=lambda x: x.pid):
        proc_rows.append([
            p.pid,
            f"{p.arrival_time:g}",
            f"{p.burst_time:g}",
            str(p.priority),
            f"{p.start_time:g}" if p.start_time is not None else "-",
            f"{p.completion_time:g}" if p.completion_time is not None else "-",
            f"{p.turnaround_time:g}" if p.turnaround_time is not None else "-",
            f"{p.waiting_time:g}" if p.waiting_time is not None else "-",
            f"{p.response_time:g}" if p.response_time is not None else "-",
        ])

    t_proc = Table(proc_rows, colWidths=[50, 58, 55, 55, 55, 65, 65, 58, 60])
    t_proc.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#1F2937")),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 8.5),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F3F4F6")]),
    ]))
    story.append(t_proc)
    story.append(Spacer(1, 14))

    # Gantt Chart Image
    if fig_gantt is not None:
        story.append(Paragraph("3. Execution Gantt Chart Timeline", heading2_style))
        img_buffer = io.BytesIO()
        fig_gantt.savefig(img_buffer, format="png", bbox_inches="tight", dpi=160)
        img_buffer.seek(0)
        # Scale image to fit within width (approx 530 points)
        rl_img = RLImage(img_buffer, width=520, height=140)
        story.append(rl_img)
        story.append(Spacer(1, 14))

    # Comparative analysis table if available
    if comparison_results and len(comparison_results) > 1:
        story.append(Paragraph("4. Multi-Algorithm Benchmark Comparison", heading2_style))
        comp_headers = ["Algorithm", "Total Time", "Idle", "Avg Waiting", "Avg TAT", "Avg RT", "CPU Util", "Throughput"]
        comp_rows = [comp_headers]
        for r in comparison_results:
            comp_rows.append([
                r.algorithm_name,
                f"{r.total_time:g}",
                f"{r.idle_time:g}",
                f"{r.avg_waiting_time:.2f}",
                f"{r.avg_turnaround_time:.2f}",
                f"{r.avg_response_time:.2f}",
                f"{r.cpu_utilization:.1f}%",
                f"{r.throughput:.3f}",
            ])
        t_comp = Table(comp_rows, colWidths=[120, 55, 45, 60, 60, 60, 60, 60])
        t_comp.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#4B5563")),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 8),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('ALIGN', (0, 1), (0, -1), 'LEFT'),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#D1D5DB")),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F9FAFB")]),
        ]))
        story.append(t_comp)

    doc.build(story)
    return buffer.getvalue()


def _export_pdf_via_matplotlib(
    result: SimulationResult,
    fig_gantt: Optional[plt.Figure] = None,
    comparison_results: Optional[List[SimulationResult]] = None
) -> bytes:
    """Fallback PDF generator using Matplotlib's native PdfPages backend."""
    from matplotlib.backends.backend_pdf import PdfPages

    buffer = io.BytesIO()
    with PdfPages(buffer) as pdf:
        # Page 1: Gantt Chart and Summary
        fig, ax = plt.subplots(figsize=(8.5, 11), dpi=100)
        ax.axis("off")

        # Title
        fig.text(0.5, 0.95, "Smart CPU Scheduling Report", ha="center", fontsize=18, fontweight="bold", color="#1E3A8A")
        fig.text(0.5, 0.92, f"Algorithm: {result.algorithm_name}", ha="center", fontsize=12, color="#4B5563")

        # Summary box
        summary_text = (
            f"Total Execution Time: {result.total_time:g} units\n"
            f"Total CPU Idle Time: {result.idle_time:g} units\n"
            f"Average Waiting Time: {result.avg_waiting_time:.2f} units\n"
            f"Average Turnaround Time: {result.avg_turnaround_time:.2f} units\n"
            f"Average Response Time: {result.avg_response_time:.2f} units\n"
            f"CPU Utilization: {result.cpu_utilization:.2f}%\n"
            f"Throughput: {result.throughput:.4f} proc/unit\n"
        )
        fig.text(0.1, 0.77, "Performance Summary:\n" + summary_text, fontsize=10, family="monospace",
                 bbox=dict(boxstyle="round,pad=0.6", facecolor="#F3F4F6", edgecolor="#D1D5DB"))

        # Table of processes
        table_data = [
            ["PID", "Arrival", "Burst", "Priority", "Start", "Completion", "Turnaround", "Waiting", "Response"]
        ]
        for p in sorted(result.processes, key=lambda x: x.pid):
            table_data.append([
                p.pid, str(p.arrival_time), str(p.burst_time), str(p.priority),
                str(p.start_time), str(p.completion_time), str(p.turnaround_time),
                str(p.waiting_time), str(p.response_time)
            ])

        table = ax.table(
            cellText=table_data,
            loc="center",
            cellLoc="center",
            bbox=[0.05, 0.40, 0.9, 0.30]
        )
        table.auto_set_font_size(False)
        table.set_fontsize(8.5)

        pdf.savefig(fig, bbox_inches="tight")
        plt.close(fig)

        # Page 2: Gantt chart if provided
        if fig_gantt is not None:
            pdf.savefig(fig_gantt, bbox_inches="tight")

    return buffer.getvalue()


def export_results_to_pdf(
    result: SimulationResult,
    fig_gantt: Optional[plt.Figure] = None,
    comparison_results: Optional[List[SimulationResult]] = None
) -> bytes:
    """Exports simulation results to a PDF byte buffer."""
    try:
        return _export_pdf_via_reportlab(result, fig_gantt, comparison_results)
    except Exception:
        # Fallback to matplotlib pdf generator
        return _export_pdf_via_matplotlib(result, fig_gantt, comparison_results)

